args <- commandArgs(trailingOnly = TRUE)
out <- normalizePath(args[1], mustWork = TRUE)
meta <- jsonlite::fromJSON(file.path(out, "proposal_record.json"))
mic <- png::readPNG(file.path(out, "proposed_patch_image_VIEW_ONLY.png"))
coverage <- png::readPNG(file.path(out, "annotation_coverage_VIEW_ONLY_RGB.png"))
context <- png::readPNG(file.path(out, "root5_context_VIEW_ONLY.png"))

# Scientific review figures only. No training mask or prediction is generated here.
png(file.path(out, "root5_proposed_patch_review.png"), width=1600, height=1010, res=130, type="cairo")
par(mar=c(0,0,0,0), xaxs="i", yaxs="i", family="sans")
plot.new(); plot.window(xlim=c(0,1600), ylim=c(1010,0))
text(38,38,"Root 5: proposed patch", adj=c(0,0.5), cex=1.8, col="#17212D")
text(38,78,"Same 1,024 x 1,024 area in both panels. Saved annotations only; no model prediction.",adj=c(0,0.5),cex=1.0,col="#465566")
text(38,126,"1  Microscopy image",adj=c(0,0.5),cex=1.2,col="#17212D")
text(826,126,"2  Your current label coverage",adj=c(0,0.5),cex=1.2,col="#17212D")
rasterImage(mic,38,884,762,160,interpolate=FALSE)
rasterImage(coverage,826,884,1550,160,interpolate=FALSE)
rect(38,160,762,884,border="#07BFCF",lwd=2)
rect(826,160,1550,884,border="#07BFCF",lwd=2)
text(1188,385,"A",cex=2.8,font=2,col="white")
text(1188,432,"Not labelled yet",cex=1.2,col="white")
text(38,920,"Red = Periderm     Green = Endoderm     Yellow = Background     Grey = unlabelled",adj=c(0,0.5),cex=1.02,col="#17212D")
text(38,954,"Grey pixels are ignored during training. They are NOT automatically Background.",adj=c(0,0.5),cex=1.0,col="#17212D")
text(38,984,"Pink = conflicting labels (6 pixels; ignored). Cyan frame = proposed patch boundary, not an annotation.",adj=c(0,0.5),cex=0.85,col="#465566")
dev.off()

png(file.path(out, "root5_patch_location.png"),width=1250,height=1050,res=125,type="cairo")
par(mar=c(1,1,5,1),family="sans",xaxs="i",yaxs="i")
box <- meta$context_xyxy_exclusive
plot.new(); plot.window(xlim=box[c(1,3)],ylim=box[c(4,2)],asp=1)
rasterImage(context,box[1],box[4],box[3],box[2],interpolate=FALSE)
crop <- meta$crop_xyxy_exclusive
rect(crop[1],crop[2],crop[3],crop[4],border="#00D6E8",lwd=3)
text(mean(crop[c(1,3)]),crop[2]+90,"Proposed 1,024 x 1,024 patch",col="white",cex=1.1)
title(main="Where the proposed patch sits on root 5",sub=NULL,cex.main=1.4,col.main="#17212D")
mtext("Cyan frame is a viewing guide only. The image and your annotations are unchanged.",side=3,line=0.8,cex=0.8,col="#465566")
dev.off()
