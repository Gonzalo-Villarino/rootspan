args <- commandArgs(trailingOnly=TRUE)
out <- normalizePath(args[1])
m <- jsonlite::fromJSON(file.path(out,"view_record.json"),simplifyVector=FALSE)
im <- png::readPNG(file.path(out,"microscopy_context_VIEW_ONLY.png"))
b <- unlist(m$crop)
png(file.path(out,"background_gap_explained.png"),width=1500,height=850,res=130,type="cairo")
par(mar=c(4.7,0.7,5.2,0.7),family="sans",xaxs="i",yaxs="i",pin=c(10,10*(b[4]-b[2])/(b[3]-b[1])))
plot.new();plot.window(xlim=b[c(1,3)],ylim=b[c(4,2)],asp=1)
rasterImage(im,b[1],b[4],b[3],b[2],interpolate=FALSE)
cols <- c(Periderm="#EB3548",Endoderm="#38C775",Background="#FFE33F")
for(s in m$shapes){
 p <- do.call(rbind,lapply(s$points,unlist))
 if(max(p[,1])<b[1] || min(p[,1])>b[3] || max(p[,2])<b[2] || min(p[,2])>b[4])next
 if(s$shape_type=="rectangle")rect(min(p[,1]),min(p[,2]),max(p[,1]),max(p[,2]),border=cols[s$label],lwd=2.4)
 else polygon(p[,1],p[,2],border=cols[s$label],col=NA,lwd=2.1)
}
text(7310,6495,"Your Background box: already done",col="#FFE33F",cex=1.2)
text(7180,6635,"This empty strip needs a label too",col="white",cex=1.25,font=2)
arrows(7450,6658,7550,6753,length=0.13,lwd=3,col="white")
title(main="Background next to the root",cex.main=1.55,col.main="#17212D",line=1.6)
mtext("Keep your existing box and tissue outlines. The white arrow only points to the remaining gap.",side=3,line=0.8,cex=0.86,col="#465566")
mtext("The black strip between the yellow box and the root is still unlabelled.",side=1,line=1.3,cex=1.02,col="#17212D")
mtext("This is a guide picture, not a new annotation or a model prediction.",side=1,line=2.9,cex=0.84,col="#465566")
dev.off()
